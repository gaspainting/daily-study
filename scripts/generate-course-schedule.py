"""Generate a shared, deterministic curriculum table for Java and JavaScript."""
from pathlib import Path
from datetime import date,timedelta
import json,re

root=Path(__file__).resolve().parent.parent
policy=json.loads((root/'docs/source/course-review-policy.json').read_text('utf-8'))
reference=(root/'docs/source/seed-reference.md').read_text('utf-8')
old={day:int(math) for day,math,vocab,total in re.findall(r'\| (2026-\d{2}-\d{2}) \| 周[一二三四五六日] \| (\d+) \| (\d+) \| (\d+) \|',reference)}
assert len(old)==70
days={}
first,last=date.fromisoformat(policy['anchor']),date.fromisoformat(policy['lastDate'])
for n in range((last-first).days+1):
    d=first+timedelta(days=n);week=policy['startWeek']+n//7;weekday=d.weekday()
    courses=[c['name'] for c in policy['courses'] if c['day']==weekday and c['firstWeek']<=week<=c['lastWeek'] and (c.get('parity')!='odd' or week%2==1)]
    review=policy['saturdayReview'] if weekday==5 else policy['sundayReview'] if weekday==6 else policy['busyReview'] if len(courses)>=policy['busyCourseCount'] else policy['lightReview']
    budget=policy['saturdayBudget'] if weekday==5 else policy['sundayBudget'] if weekday==6 else policy['weekdayBudget']
    assert review<budget and 0<=review<=1440
    days[d.isoformat()]={'week':week,'weekday':weekday,'courses':courses,'review':review,'math':budget-review,'legacyMath':old[d.isoformat()]}
data={key:policy[key] for key in ('version','effectiveFrom','anchor','lastDate','subjectId','subjectName','legacyTitle','title','legacyMathDefaults','weekdayBudget','saturdayBudget','sundayBudget','lightReview','saturdayReview','sundayReview')}
data['days']=days
assets=root/'app/src/main/assets'
compact=json.dumps(data,ensure_ascii=False,separators=(',',':'))
(assets/'course-schedule-data.js').write_text('(function(root){\n  "use strict";\n  var data='+compact+';\n  if(typeof module==="object"&&module.exports)module.exports=data;\n  root.StudyCourseData=data;\n})(typeof globalThis!=="undefined"?globalThis:this);\n','utf-8')
java=root/'app/src/main/java/cn/edu/njupt/studycheckin/CourseScheduleData.java'
java.write_text('package cn.edu.njupt.studycheckin;\n\n/** Generated by scripts/generate-course-schedule.py. */\nfinal class CourseScheduleData {\n    static final String JSON='+json.dumps(compact,ensure_ascii=False)+';\n    private CourseScheduleData() {}\n}\n','utf-8')
assert len(compact.encode('utf-8'))<60000
print(json.dumps({'days':len(days),'effectiveFrom':policy['effectiveFrom'],'weekdayBudget':policy['weekdayBudget'],'javaAndJsShareTable':True,'weeklyTotals':[{ 'week':7+i,'review':sum(v['review'] for v in list(days.values())[i*7:i*7+7]),'math':sum(v['math'] for v in list(days.values())[i*7:i*7+7])} for i in range(10)]},ensure_ascii=False))
