  const escape=value=>String(value).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  function view(){
    const list=(tag,items)=>'<'+tag+'>'+items.map(x=>'<li>'+escape(x)+'</li>').join('')+'</'+tag+'>';
    return '<article class="user-manual" aria-label="使用手册内容"><nav class="manual-toc" aria-label="使用手册目录">'+chapters.map(c=>'<button type="button" data-action="manual-section" data-section="'+c.id+'">'+escape(c.title)+'</button>').join('')+'</nav>'+chapters.map((c,i)=>'<details class="manual-chapter" id="manual-'+c.id+'"'+(i===0?' open':'')+'><summary>'+escape(c.title)+'</summary><div class="manual-body">'+c.parts.map(p=>(p.title?'<h3>'+escape(p.title)+'</h3>':'')+(p.text?p.text.map(t=>'<p>'+escape(t)+'</p>').join(''):'')+(p.steps?list('ol',p.steps):'')+(p.items?list('ul',p.items):'')).join('')+'</div></details>').join('')+'</article>';
  }
  function section(id){
    const e=document.getElementById('manual-'+id);
    if(!e||!e.closest('.user-manual'))return;
    e.open=true;
    const sheet=document.getElementById('sheet'),heading=sheet.querySelector('.sheet-heading');
    sheet.scrollTop+=e.getBoundingClientRect().top-heading.getBoundingClientRect().bottom-12;
    e.querySelector('summary').focus({preventScroll:true});
  }
  function top(){
    const toc=document.querySelector('.manual-toc');
    if(!toc)return;
    document.getElementById('sheet').scrollTop=0;toc.querySelector('button').focus({preventScroll:true});
  }
